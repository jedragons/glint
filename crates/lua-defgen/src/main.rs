//! lua-defgen
//!
//! Scans each `<sources>/<lib>/src` directory (recursively -- bindings are
//! not confined to a single `bindings/` subdirectory, and live at different
//! depths in different libraries) for C/C++ source files, extracts `/*@ ... */`
//! comment blocks, dedents them, and writes one `<definitions>/<lib>/<relative-path>.lua`
//! file per source file containing all of its extracted blocks (prefixed with
//! `---@meta`). Source files with no such blocks are simply skipped, so it is
//! safe to point this at a whole library's `src/` tree.
//!
//! Only files corresponding to annotated sources are written. Existing files
//! that are no longer generated are retained and must be reviewed manually.
//! The C rewrite currently has no annotation blocks, so the checked-in
//! definitions are maintained manually rather than generated by this tool.
//!
//! This tool does no validation or sync-checking -- it only extracts text.
//!
//! Usage:
//!     lua-defgen [SOURCES_DIR] [DEFINITIONS_DIR]
//!
//! Defaults: SOURCES_DIR=sources, DEFINITIONS_DIR=definitions

use std::collections::BTreeMap;
use std::env;
use std::fs;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result, bail};
use walkdir::WalkDir;

/// File extensions treated as C/C++ sources/headers worth scanning.
const SOURCE_EXTENSIONS: &[&str] = &["c", "cpp", "cc", "cxx", "hpp", "hh", "h"];

/// Marks the start of an extractable block. Must appear alone on its line
/// (whitespace-trimmed).
const BLOCK_OPEN: &str = "/*@";

/// Marks the end of an extractable block. Must appear alone on its line
/// (whitespace-trimmed).
const BLOCK_CLOSE: &str = "*/";

fn main() -> Result<()> {
    let mut args = env::args().skip(1);
    let sources_dir = PathBuf::from(args.next().unwrap_or_else(|| "sources".to_string()));
    let definitions_dir = PathBuf::from(args.next().unwrap_or_else(|| "definitions".to_string()));
    if args.next().is_some() {
        bail!("usage: lua-defgen [SOURCES_DIR] [DEFINITIONS_DIR]");
    }

    if !sources_dir.is_dir() {
        bail!(
            "sources directory `{}` does not exist",
            sources_dir.display()
        );
    }

    let mut outputs = BTreeMap::new();

    for lib_entry in fs::read_dir(&sources_dir)
        .with_context(|| format!("reading sources dir `{}`", sources_dir.display()))?
    {
        let lib_entry = lib_entry?;
        if !lib_entry.file_type()?.is_dir() {
            continue;
        }

        let lib_name = lib_entry.file_name().to_string_lossy().into_owned();
        let src_dir = lib_entry.path().join("src");

        if !src_dir.is_dir() {
            continue;
        }

        process_src_dir(&src_dir, &lib_name, &definitions_dir, &mut outputs)?;
    }

    if outputs.is_empty() {
        bail!("no annotation blocks found; existing definitions were not changed");
    }
    for (out_path, (_, output)) in outputs {
        if let Some(parent) = out_path.parent() {
            fs::create_dir_all(parent)
                .with_context(|| format!("creating dir `{}`", parent.display()))?;
        }
        fs::write(&out_path, output)
            .with_context(|| format!("writing `{}`", out_path.display()))?;
        println!("wrote {}", out_path.display());
    }

    Ok(())
}

/// Collect outputs before writing, so traversal errors and collisions do not
/// silently discard or overwrite definitions.
fn process_src_dir(
    src_dir: &Path,
    lib_name: &str,
    definitions_dir: &Path,
    outputs: &mut BTreeMap<PathBuf, (PathBuf, String)>,
) -> Result<()> {
    for entry in WalkDir::new(src_dir) {
        let entry = entry?;
        if !entry.file_type().is_file() {
            continue;
        }

        let path = entry.path();
        let ext = path.extension().and_then(|e| e.to_str()).unwrap_or("");
        if !SOURCE_EXTENSIONS.contains(&ext) {
            continue;
        }

        let content =
            fs::read_to_string(path).with_context(|| format!("reading `{}`", path.display()))?;

        let blocks = extract_blocks(&content)
            .with_context(|| format!("reading annotations in `{}`", path.display()))?;
        if blocks.is_empty() {
            continue;
        }

        let relative = path.strip_prefix(src_dir).unwrap_or(path);
        let mut out_path = definitions_dir.join(lib_name).join(relative);
        out_path.set_extension("lua");

        let mut output = String::from("---@meta\n\n");
        output.push_str(&blocks.join("\n\n"));
        output.push('\n');

        if let Some((previous, _)) = outputs.insert(out_path.clone(), (path.to_path_buf(), output))
        {
            bail!(
                "sources `{}` and `{}` both map to `{}`",
                previous.display(),
                path.display(),
                out_path.display()
            );
        }
    }

    Ok(())
}

/// Extracts each `/*@ ... */` block (delimiters must sit alone on their own
/// line) from `content`, dedents its contents, and returns the blocks in
/// source order. An unterminated block is an error.
fn extract_blocks(content: &str) -> Result<Vec<String>> {
    let mut blocks = Vec::new();
    let mut current: Option<Vec<&str>> = None;

    for line in content.lines() {
        let trimmed = line.trim();

        match &mut current {
            None => {
                if trimmed == BLOCK_OPEN {
                    current = Some(Vec::new());
                }
            }
            Some(buf) => {
                if trimmed == BLOCK_CLOSE {
                    blocks.push(dedent(buf));
                    current = None;
                } else {
                    buf.push(line);
                }
            }
        }
    }

    if current.is_some() {
        bail!("unterminated annotation block");
    }
    Ok(blocks)
}

/// Removes the smallest common leading-space indentation shared by all
/// non-blank lines. Blank lines are emitted as empty strings.
fn dedent(lines: &[&str]) -> String {
    let min_indent = lines
        .iter()
        .filter(|l| !l.trim().is_empty())
        .map(|l| l.len() - l.trim_start_matches(' ').len())
        .min()
        .unwrap_or(0);

    lines
        .iter()
        .map(|l| {
            if l.trim().is_empty() {
                ""
            } else if l.len() >= min_indent {
                &l[min_indent..]
            } else {
                l.trim_start()
            }
        })
        .collect::<Vec<_>>()
        .join("\n")
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::sync::atomic::{AtomicUsize, Ordering};

    #[test]
    fn extracts_and_dedents_blocks() {
        let blocks =
            extract_blocks("code\n  /*@\n    ---@class Foo\n    Foo = {}\n  */\n").unwrap();
        assert_eq!(blocks, ["---@class Foo\nFoo = {}"]);
        assert!(extract_blocks("/*@\nunfinished").is_err());
    }

    #[test]
    fn scans_c_and_detects_output_collisions() {
        static NEXT: AtomicUsize = AtomicUsize::new(0);
        let root = env::temp_dir().join(format!(
            "lua-defgen-{}-{}",
            std::process::id(),
            NEXT.fetch_add(1, Ordering::Relaxed)
        ));
        let src = root.join("src");
        fs::create_dir_all(&src).unwrap();
        fs::write(src.join("binding.c"), "/*@\nFoo = {}\n*/\n").unwrap();
        let mut outputs = BTreeMap::new();
        process_src_dir(&src, "lib", &root.join("definitions"), &mut outputs).unwrap();
        assert_eq!(outputs.len(), 1);
        assert!(outputs.values().next().unwrap().1.contains("Foo = {}"));
        fs::write(src.join("binding.cpp"), "/*@\nBar = {}\n*/\n").unwrap();
        assert!(
            process_src_dir(&src, "lib", &root.join("definitions"), &mut BTreeMap::new()).is_err()
        );
        fs::remove_dir_all(root).unwrap();
    }
}
